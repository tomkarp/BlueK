// Generates `frontend/src/standardImages.generated.ts` from the graphics in
// `assets/standard-images/`. The graphics ship inside the bundle, including
// their pixel masks, so a project can use them without a network round trip and
// without decoding an image before the first compile. Run this after adding or
// removing a file there.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repository = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const folder = path.join(repository, 'assets/standard-images');

/** Two hexadecimal alpha digits per pixel, row-major — the format the runtime expects. */
function alphaOf(png) {
  if (png.readUInt32BE(0) !== 0x89504e47) throw new Error('Not a PNG file.');
  let offset = 8;
  let header = null;
  const parts = [];
  while (offset < png.length) {
    const length = png.readUInt32BE(offset);
    const type = png.toString('ascii', offset + 4, offset + 8);
    const data = png.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') header = {
      width: data.readUInt32BE(0),
      height: data.readUInt32BE(4),
      depth: data[8],
      color: data[9],
      interlace: data[12],
    };
    else if (type === 'IDAT') parts.push(data);
    else if (type === 'IEND') break;
    offset += length + 12;
  }
  if (!header) throw new Error('The PNG has no header.');
  if (header.depth !== 8 || header.color !== 6 || header.interlace !== 0)
    throw new Error('Only non-interlaced 8-bit RGBA PNG files are supported.');
  const { width, height } = header;
  const raw = inflateSync(Buffer.concat(parts));
  const stride = width * 4;
  const pixels = Buffer.alloc(stride * height);
  for (let row = 0; row < height; row += 1) {
    const filter = raw[row * (stride + 1)];
    const line = raw.subarray(row * (stride + 1) + 1, (row + 1) * (stride + 1));
    const target = pixels.subarray(row * stride, (row + 1) * stride);
    const previous = row === 0 ? Buffer.alloc(stride) : pixels.subarray((row - 1) * stride, row * stride);
    for (let index = 0; index < stride; index += 1) {
      const left = index >= 4 ? target[index - 4] : 0;
      const up = previous[index];
      const upLeft = index >= 4 ? previous[index - 4] : 0;
      let value = line[index];
      if (filter === 1) value += left;
      else if (filter === 2) value += up;
      else if (filter === 3) value += (left + up) >> 1;
      else if (filter === 4) {
        const estimate = left + up - upLeft;
        const distanceLeft = Math.abs(estimate - left);
        const distanceUp = Math.abs(estimate - up);
        const distanceUpLeft = Math.abs(estimate - upLeft);
        value += distanceLeft <= distanceUp && distanceLeft <= distanceUpLeft ? left
          : distanceUp <= distanceUpLeft ? up : upLeft;
      } else if (filter !== 0) throw new Error(`Unknown PNG filter ${filter}.`);
      target[index] = value & 0xff;
    }
  }
  let alphaHex = '';
  for (let index = 3; index < pixels.length; index += 4) alphaHex += pixels[index].toString(16).padStart(2, '0');
  return { width, height, alphaHex };
}

const names = (await readdir(folder))
  .filter((name) => name.toLowerCase().endsWith('.png'))
  .sort((first, second) => first.localeCompare(second, 'en'));
const entries = await Promise.all(names.map(async (name) => {
  const png = await readFile(path.join(folder, name));
  const { width, height, alphaHex } = alphaOf(png);
  return `  {\n    path: "images/${name}",\n    data: "data:image/png;base64,${png.toString('base64')}",\n    imageWidth: ${width},\n    imageHeight: ${height},\n    alphaHex: "${alphaHex}",\n  },`;
}));
await writeFile(path.join(repository, 'frontend/src/standardImages.generated.ts'), `// Generated by scripts/build-standard-images.mjs - do not edit.
import type { ProjectResource } from "../../runtime-contract/src/index";

export const STANDARD_IMAGES: ProjectResource[] = [
${entries.join('\n')}
];
`);
console.log(`Standard graphics: ${names.length} files generated.`);
